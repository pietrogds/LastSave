let alternativas = ["alternativaA", "alternativaB", "alternativaC", "alternativaD"];

let quantidadeDeQuestoes = listaDeQuestoes.length;
let numeroDaQuestaoAtual = 0;
let certas = 0;
let erradas = 0;
let acertosHistoria = 0;
let acertosCriador = 0;

function iniciarQuiz() {
    numeroDaQuestaoAtual = 0;
    certas = 0;
    erradas = 0;
    acertosHistoria = 0;
    acertosCriador = 0;

    span_certas.innerHTML = 0;
    span_erradas.innerHTML = 0;
    span_total.innerHTML = quantidadeDeQuestoes;

    intro_quiz.style.display = "none";
    resultado_quiz.style.display = "none";
    jogo_quiz.style.display = "block";

    mostrarQuestao();
}

function mostrarQuestao() {
    let questao = listaDeQuestoes[numeroDaQuestaoAtual];
    let radios = [opcao_a, opcao_b, opcao_c, opcao_d];
    let labels = [label_a, label_b, label_c, label_d];

    span_numero.innerHTML = numeroDaQuestaoAtual + 1;
    barra_progresso.style.width = (numeroDaQuestaoAtual * 100) / quantidadeDeQuestoes + "%";

    if (questao.categoria == "historia") {
        selo_categoria.innerHTML = "História dos games";
        selo_categoria.className = "selo";
    } else {
        selo_categoria.innerHTML = "Sobre o criador do LastSave";
        selo_categoria.className = "selo selo-azul";
    }

    pergunta_quiz.innerHTML = questao.pergunta;
    texto_a.innerHTML = questao.alternativaA;
    texto_b.innerHTML = questao.alternativaB;
    texto_c.innerHTML = questao.alternativaC;
    texto_d.innerHTML = questao.alternativaD;

    for (let i = 0; i < radios.length; i++) {
        radios[i].checked = false;
        radios[i].disabled = false;
        labels[i].className = "opcao";
    }

    aviso_quiz.innerHTML = "";
    btn_responder.style.display = "inline-block";
    btn_proxima.style.display = "none";
}

function responder() {
    let questao = listaDeQuestoes[numeroDaQuestaoAtual];
    let radios = [opcao_a, opcao_b, opcao_c, opcao_d];
    let labels = [label_a, label_b, label_c, label_d];

    let escolhida = -1;
    let correta = -1;

    for (let i = 0; i < radios.length; i++) {
        if (radios[i].checked) {
            escolhida = i;
        }
        if (alternativas[i] == questao.alternativaCorreta) {
            correta = i;
        }
    }

    if (escolhida == -1) {
        aviso_quiz.innerHTML = "Escolha uma alternativa antes de responder!";
    } else {
        labels[correta].className = "opcao opcao-certa";

        if (escolhida == correta) {
            certas++;
            aviso_quiz.innerHTML = "Acertou! +1 ponto";

            if (questao.categoria == "historia") {
                acertosHistoria++;
            } else {
                acertosCriador++;
            }
        } else {
            erradas++;
            labels[escolhida].className = "opcao opcao-errada";
            aviso_quiz.innerHTML = "Errou! A resposta certa está em verde.";
        }

        for (let i = 0; i < radios.length; i++) {
            radios[i].disabled = true;
        }

        span_certas.innerHTML = certas;
        span_erradas.innerHTML = erradas;

        btn_responder.style.display = "none";
        btn_proxima.style.display = "inline-block";

        if (numeroDaQuestaoAtual == quantidadeDeQuestoes - 1) {
            btn_proxima.innerHTML = "Ver resultado";
        } else {
            btn_proxima.innerHTML = "Próxima questão";
        }
    }
}

function proximaQuestao() {
    numeroDaQuestaoAtual++;

    if (numeroDaQuestaoAtual < quantidadeDeQuestoes) {
        mostrarQuestao();
    } else {
        finalizarQuiz();
    }
}

function finalizarQuiz() {
    let porcentagem = Math.round((certas * 100) / quantidadeDeQuestoes);
    let totalHistoria = 0;
    let totalCriador = 0;

    for (let i = 0; i < quantidadeDeQuestoes; i++) {
        if (listaDeQuestoes[i].categoria == "historia") {
            totalHistoria++;
        } else {
            totalCriador++;
        }
    }

    let mensagem = "";

    if (porcentagem >= 90) {
        mensagem = "LENDÁRIO! Você zerou o quiz!";
    } else if (porcentagem >= 60) {
        mensagem = "Mandou bem! Falta pouco para o 100%.";
    } else if (porcentagem >= 30) {
        mensagem = "Dá para melhorar! Que tal reler a aba História?";
    } else {
        mensagem = "GAME OVER! Volte nas abas do site e tente de novo.";
    }

    jogo_quiz.style.display = "none";
    resultado_quiz.style.display = "block";

    titulo_resultado.innerHTML = mensagem;
    texto_resultado.innerHTML =
        "Você acertou <b>" + certas + " de " + quantidadeDeQuestoes + "</b> perguntas (<b>" + porcentagem + "%</b>).";
    detalhe_historia.innerHTML = acertosHistoria + " / " + totalHistoria;
    detalhe_criador.innerHTML = acertosCriador + " / " + totalCriador;

    salvarResultado();
}

function salvarResultado() {
    status_salvar.innerHTML = "Salvando seu resultado...";

    fetch("/quiz/registrar", {
        method: "POST",
        headers: {
            "Content-Type": "application/json"
        },
        body: JSON.stringify({
            acertosServer: certas,
            acertosHistoriaServer: acertosHistoria,
            acertosCriadorServer: acertosCriador,
            totalPerguntasServer: quantidadeDeQuestoes,
            idUsuarioServer: sessionStorage.ID_USUARIO
        })
    }).then(function (resposta) {
        if (resposta.ok) {
            status_salvar.innerHTML = "Resultado salvo! Confira sua dashboard logo abaixo.";
            carregarDashboard();
        } else {
            status_salvar.innerHTML = "Não foi possível salvar seu resultado.";
        }
    }).catch(function (erro) {
        console.log(erro);
        status_salvar.innerHTML = "Não foi possível salvar seu resultado.";
    });
}
